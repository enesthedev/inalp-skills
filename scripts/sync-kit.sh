#!/usr/bin/env bash
# Rebuild the inalp-artifacts kit from the İnalp site repo.
# Usage: scripts/sync-kit.sh [path-to-inalp-repo]   (default: ../inalp)
# Maintainer-only. Needs macOS `sips` (photo resize) and python3.
set -euo pipefail

SRC="${1:-$(dirname "$0")/../../inalp}"
SKILL="$(cd "$(dirname "$0")/.." && pwd)/skills/inalp-artifacts"
[ -d "$SRC/public/egitmenler" ] || { echo "Not the inalp repo: $SRC" >&2; exit 1; }

rm -rf "$SKILL/assets/brand/"*.png "$SKILL/assets/brand/favicon.svg" \
  "$SKILL/assets/tutors" "$SKILL/assets/universities" "$SKILL/references/data"
mkdir -p "$SKILL/assets/brand" "$SKILL/assets/tutors" "$SKILL/assets/universities" "$SKILL/references/data"

cp "$SRC/public/inalp-ikon.png" "$SRC/public/og-logo.png" "$SRC/public/favicon.svg" "$SKILL/assets/brand/"
cp "$SRC/public/universiteler/"*.png "$SKILL/assets/universities/"

# Originals are ~2300x3100 and 1-2 MB; 1400px on the long edge still fills a 1080x1350 slide.
(cd "$SRC/public/egitmenler" && find . -name '*.jpg') | while read -r f; do
  mkdir -p "$SKILL/assets/tutors/$(dirname "$f")"
  sips -Z 1400 -s formatOptions 70 "$SRC/public/egitmenler/$f" --out "$SKILL/assets/tutors/$f" >/dev/null
done

for f in tutors testimonials programs faq settings team-roles universities cities coverage-provinces; do
  cp "$SRC/data/$f.json" "$SKILL/references/data/"
done

python3 - "$SKILL" <<'PY'
import json, os, sys
skill = sys.argv[1]
data = os.path.join(skill, "references", "data")

def rewrite(name, key, old, new):
    path = os.path.join(data, name)
    raw = json.load(open(path))
    items = raw["tutors"] if isinstance(raw, dict) else raw
    for it in items:
        it[key] = it[key].replace(old, new, 1)
    json.dump(raw, open(path, "w"), ensure_ascii=False, indent=2)
    return items

tutors = rewrite("tutors.json", "photo", "/egitmenler/", "assets/tutors/")
unis = rewrite("universities.json", "logo", "/universiteler/", "assets/universities/")

missing = [p for p in [t["photo"] for t in tutors] + [u["logo"] for u in unis]
           if not os.path.isfile(os.path.join(skill, p))]
if missing:
    sys.exit("Missing files:\n" + "\n".join(missing))

settings = json.load(open(os.path.join(data, "settings.json")))
lines = [
    "# Kit index",
    "",
    "Generated by `scripts/sync-kit.sh` from the İnalp site. Do not edit by hand.",
    "Paths are relative to the skill folder.",
    "",
    "## Contact",
    "",
    f"- Phone: {settings['phone']['display']} (WhatsApp {settings['phone']['whatsapp']})",
    f"- Instagram: @{settings['social']['instagram']}",
    "- Website: https://inalpakademi.com",
    "",
    "## Brand",
    "",
    "- `assets/brand/inalp-ikon.png`: the mark, 500x500",
    "- `assets/brand/og-logo.png`: mark on its tile, 1000x1000",
    "- `assets/brand/favicon.svg`",
    "- `assets/brand/wordmark.html`: icon + İnalp Akademi wordmark in HTML/CSS",
    "",
    f"## Tutors ({len(tutors)})",
    "",
    "| Name | City | University | Rank | Photo |",
    "| --- | --- | --- | --- | --- |",
]
for t in sorted(tutors, key=lambda t: (t["city"], t["name"])):
    lines.append(f"| {t['name']} | {t['city']} | {t['university']} | {t.get('rank', '')} | `{t['photo']}` |")
lines += ["", f"## University crests ({len(unis)})", "", "| University | File |", "| --- | --- |"]
for u in unis:
    lines.append(f"| {u['name']} | `{u['logo']}` |")
open(os.path.join(skill, "references", "kit-index.md"), "w").write("\n".join(lines) + "\n")
print(f"OK: {len(tutors)} tutors, {len(unis)} crests")
PY
